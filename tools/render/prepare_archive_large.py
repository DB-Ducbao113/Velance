#!/usr/bin/env python3
"""Build a 2560px gallery tier only from existing verified >=2560px photos.

The source is the archived viewer WebP, not an independently retrieved JPEG.
No interpolation to larger dimensions. The full viewer asset remains unchanged.
"""
import hashlib
import json
from pathlib import Path
from PIL import Image

ROOT=Path(__file__).resolve().parents[2]
manifest_paths=['photo-archive.js','photo-archive-a.js','photo-archive-b.js']
catalog={}
for name in manifest_paths:
    raw=(ROOT/'src/data'/name).read_text();catalog.update(json.loads(raw.split(' = ',1)[1].strip().rstrip(';')))
output=ROOT/'src/data/archive-large.js'
previous=json.loads(output.read_text().split(' = ',1)[1].strip().rstrip(';')) if output.exists() else {}
result={};lines=['# VÉLANCE — high-DPI gallery derivatives','','The 2560px tier is derived from the verified full viewer WebP, retaining its source license and composition. It is a secondary downsample/re-encode, not a separately downloaded original and not an upscale. Full-size photos remain reserved for the viewer.','','| Viewer source | Gallery variant | Dimensions | Bytes | SHA-256 |','| --- | --- | --- | ---: | --- |']
for car,records in catalog.items():
    for p in records:
        if p['width']<=2560:continue
        src=ROOT/p['full'];target=src.with_name(src.stem.rsplit('-',1)[0]+'-2560.webp')
        with Image.open(src) as im:
            assert im.size==(p['width'],p['height'])
            height=round(im.height*2560/im.width);im.convert('RGB').resize((2560,height),Image.Resampling.LANCZOS).save(target,'WEBP',quality=90,method=6)
        rel='./'+target.relative_to(ROOT).as_posix();data=target.read_bytes();sha=hashlib.sha256(data).hexdigest()
        result[p['full']]={'large':rel,'largeWidth':2560}
        lines.append(f"| `{p['full']}` | `{rel}` | 2560 × {height} | {len(data)} | `{sha}` |")
active={v['large'] for v in result.values()}|{p[k] for records in catalog.values() for p in records for k in ('thumb','medium','full')}
for v in previous.values():
    old=v['large'];path=(ROOT/old).resolve()
    if old not in active and path.is_relative_to(ROOT/'assets/archive') and path.name.endswith('-2560.webp'):path.unlink(missing_ok=True)
output.write_text('// Generated by tools/render/prepare_archive_large.py.\nexport const ARCHIVE_LARGE = '+json.dumps(result,indent=2)+';\n')
(ROOT/'docs/frontend-photo-large.md').write_text('\n'.join(lines)+'\n')
print('Large gallery derivatives:',len(result))
